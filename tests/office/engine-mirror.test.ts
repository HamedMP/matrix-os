import { spawnSync } from "node:child_process";
import fs, { cpSync, existsSync, lstatSync, mkdirSync, mkdtempSync, readFileSync, readdirSync, rmSync, symlinkSync, utimesSync, writeFileSync } from "node:fs";
import { syncBuiltinESMExports } from "node:module";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { pathToFileURL } from "node:url";
import { afterEach, describe, expect, it } from "vitest";

import { generateTemplateManifest } from "../../packages/kernel/src/boot.js";
import { OFFICE_ERROR_CODES, OfficeError, isOfficeError } from "../../packages/office/src/errors.js";
// Generated by the vitest global setup (tests/helpers/office-engine-global-setup.ts); not tracked.
import * as mirroredErrors from "../../home/apps/_shared/office-engine/errors.js";

const root = process.cwd();
const script = join(root, "scripts/sync-office-engine.mjs");
const SOURCE = "packages/office/src";
const MIRROR = "home/apps/_shared/office-engine";

type Change = { path: string; action: "add" | "update" | "delete" };
type SyncModule = {
  syncOfficeEngine(options: { root: string; check?: boolean }): { changes: Change[] };
  STALE_TEMPORARY_MS: number;
};
const load = (): Promise<SyncModule> => import(pathToFileURL(script).href);

const temporaryRoots: string[] = [];
function makeRoot(files: Record<string, string>): string {
  const directory = mkdtempSync(join(tmpdir(), "office-engine-mirror-"));
  temporaryRoots.push(directory);
  for (const [path, content] of Object.entries(files)) write(directory, path, content);
  return directory;
}
function write(directory: string, path: string, content: string): void {
  mkdirSync(dirname(join(directory, path)), { recursive: true });
  writeFileSync(join(directory, path), content);
}
function listFiles(directory: string, prefix = ""): string[] {
  return readdirSync(join(directory, prefix), { withFileTypes: true })
    .flatMap((entry) =>
      entry.isDirectory() ? listFiles(directory, `${prefix}${entry.name}/`) : [`${prefix}${entry.name}`],
    )
    .sort();
}

afterEach(() => {
  for (const directory of temporaryRoots.splice(0)) rmSync(directory, { recursive: true, force: true });
});

/** A scratch checkout holding the real engine source and the given repository files. */
function makeCheckout(files: string[]): string {
  const directory = makeRoot({});
  cpSync(join(root, SOURCE), join(directory, SOURCE), { recursive: true });
  for (const file of files) {
    mkdirSync(dirname(join(directory, file)), { recursive: true });
    cpSync(join(root, file), join(directory, file));
  }
  return directory;
}
const git = (...args: string[]) => spawnSync("git", args, { cwd: root, encoding: "utf8", timeout: 30_000 });

describe("office engine mirror", () => {
  it("generates a byte-for-byte copy of packages/office/src, and a second run changes nothing", async () => {
    const { syncOfficeEngine } = await load();
    const directory = makeCheckout([]);

    const first = syncOfficeEngine({ root: directory }).changes;
    const sourceFiles = listFiles(join(directory, SOURCE));
    expect(sourceFiles.length).toBeGreaterThan(20);
    expect(first).toEqual(["README.md", ...sourceFiles].sort().map((path) => ({ path, action: "add" })));
    expect(listFiles(join(directory, MIRROR))).toEqual(["README.md", ...sourceFiles].sort());
    for (const path of sourceFiles) {
      expect(readFileSync(join(directory, MIRROR, path)).equals(readFileSync(join(directory, SOURCE, path))), path).toBe(true);
    }

    expect(syncOfficeEngine({ root: directory }).changes).toEqual([]);
    expect(syncOfficeEngine({ root: directory, check: true }).changes).toEqual([]);
  });

  it("is git-ignored and has no tracked files, so the generated copy is never committed", () => {
    const ignored = git("check-ignore", "--no-index", "-q", `${MIRROR}/index.ts`);
    expect(ignored.status, ignored.stderr).toBe(0);
    const tracked = git("ls-files", "--", MIRROR);
    expect(tracked.status, tracked.stderr).toBe(0);
    expect(tracked.stdout).toBe("");
    // The helper that regenerates it before an app build must stay tracked.
    expect(git("ls-files", "--error-unmatch", "home/apps/_shared/ensure-office-engine.mjs").status).toBe(0);
  });

  it("copies the source tree byte for byte and adds a generated notice", async () => {
    const { syncOfficeEngine } = await load();
    const crlf = "export const a = 1;\r\n// café\r\n";
    const directory = makeRoot({ [`${SOURCE}/index.ts`]: crlf, [`${SOURCE}/api/deep/types.ts`]: "export type T = 1;\n" });

    const { changes } = syncOfficeEngine({ root: directory });

    expect(changes).toEqual([
      { path: "README.md", action: "add" },
      { path: "api/deep/types.ts", action: "add" },
      { path: "index.ts", action: "add" },
    ]);
    expect(listFiles(join(directory, MIRROR))).toEqual(["README.md", "api/deep/types.ts", "index.ts"]);
    expect(readFileSync(join(directory, MIRROR, "index.ts"))).toEqual(Buffer.from(crlf));
    expect(readFileSync(join(directory, MIRROR, "README.md"), "utf8")).toMatch(/^<!-- GENERATED/);
    expect(syncOfficeEngine({ root: directory, check: true }).changes).toEqual([]);
  });

  it("reports changed, new and removed files in check mode without writing", async () => {
    const { syncOfficeEngine } = await load();
    const directory = makeRoot({ [`${SOURCE}/index.ts`]: "one\n", [`${SOURCE}/old.ts`]: "old\n" });
    syncOfficeEngine({ root: directory });

    write(directory, `${SOURCE}/index.ts`, "two\n");
    write(directory, `${SOURCE}/added.ts`, "added\n");
    rmSync(join(directory, SOURCE, "old.ts"));
    write(directory, `${MIRROR}/README.md`, "edited by hand\n");

    expect(syncOfficeEngine({ root: directory, check: true }).changes).toEqual([
      { path: "README.md", action: "update" },
      { path: "added.ts", action: "add" },
      { path: "index.ts", action: "update" },
      { path: "old.ts", action: "delete" },
    ]);
    expect(readFileSync(join(directory, MIRROR, "index.ts"), "utf8")).toBe("one\n");
    expect(listFiles(join(directory, MIRROR))).toEqual(["README.md", "index.ts", "old.ts"]);
  });

  it("deletes mirrored files whose source is gone and prunes empty directories", async () => {
    const { syncOfficeEngine } = await load();
    const directory = makeRoot({ [`${SOURCE}/index.ts`]: "one\n", [`${SOURCE}/gone/deep/file.ts`]: "gone\n" });
    syncOfficeEngine({ root: directory });
    rmSync(join(directory, SOURCE, "gone"), { recursive: true });

    expect(syncOfficeEngine({ root: directory }).changes).toEqual([{ path: "gone/deep/file.ts", action: "delete" }]);
    expect(listFiles(join(directory, MIRROR))).toEqual(["README.md", "index.ts"]);
    expect(readdirSync(join(directory, MIRROR)).sort()).toEqual(["README.md", "index.ts"]);
  });

  it("refuses symbolic links and a source file that collides with the generated notice", async () => {
    const { syncOfficeEngine } = await load();
    const linked = makeRoot({ [`${SOURCE}/index.ts`]: "one\n", "outside.ts": "secret\n" });
    symlinkSync(join(linked, "outside.ts"), join(linked, SOURCE, "link.ts"));
    expect(() => syncOfficeEngine({ root: linked })).toThrow(/symbolic link/);

    const colliding = makeRoot({ [`${SOURCE}/README.md`]: "notes\n" });
    expect(() => syncOfficeEngine({ root: colliding })).toThrow(/README\.md/);
  });

  it("removes its temporary file when publishing a mirrored file fails", async () => {
    const { syncOfficeEngine } = await load();
    const directory = makeRoot({ [`${SOURCE}/index.ts`]: "one\n" });
    const rename = fs.renameSync;
    fs.renameSync = () => {
      throw Object.assign(new Error("cross-device link"), { code: "EXDEV" });
    };
    syncBuiltinESMExports();
    try {
      expect(() => syncOfficeEngine({ root: directory })).toThrow(/cross-device/);
    } finally {
      fs.renameSync = rename;
      syncBuiltinESMExports();
    }
    expect(listFiles(join(directory, MIRROR))).toEqual([]);
  });

  it("sweeps abandoned temporary files, but keeps a running sync's fresh one and never follows a symbolic link", async () => {
    const { syncOfficeEngine, STALE_TEMPORARY_MS } = await load();
    const directory = makeRoot({ [`${SOURCE}/index.ts`]: "one\n", "outside.ts": "keep\n" });
    syncOfficeEngine({ root: directory });
    const mirror = join(directory, MIRROR);
    const old = new Date(Date.now() - STALE_TEMPORARY_MS - 60_000);
    write(mirror, "index.ts.office-sync-111-1.tmp", "abandoned\n");
    write(mirror, "deep/x.ts.office-sync-111-2.tmp", "abandoned\n");
    utimesSync(join(mirror, "index.ts.office-sync-111-1.tmp"), old, old);
    utimesSync(join(mirror, "deep/x.ts.office-sync-111-2.tmp"), old, old);
    write(mirror, "index.ts.office-sync-222-1.tmp", "being written\n");
    symlinkSync(join(directory, "outside.ts"), join(mirror, "link.ts.office-sync-333-1.tmp"));
    const link = join(mirror, "link.ts.office-sync-333-1.tmp");
    fs.lutimesSync(link, old, old);

    expect(syncOfficeEngine({ root: directory, check: true }).changes).toEqual([]);
    expect(existsSync(join(mirror, "index.ts.office-sync-111-1.tmp"))).toBe(true);

    expect(syncOfficeEngine({ root: directory }).changes).toEqual([]);
    expect(existsSync(join(mirror, "index.ts.office-sync-111-1.tmp"))).toBe(false);
    expect(existsSync(join(mirror, "deep"))).toBe(false);
    expect(readFileSync(join(mirror, "index.ts.office-sync-222-1.tmp"), "utf8")).toBe("being written\n");
    expect(lstatSync(link).isSymbolicLink()).toBe(true);
    expect(readFileSync(join(directory, "outside.ts"), "utf8")).toBe("keep\n");
  });

  it("exits 1 from the command line when the mirror is stale and 0 after a sync", () => {
    const directory = makeRoot({ [`${SOURCE}/index.ts`]: "one\n" });
    const run = (...args: string[]) =>
      spawnSync(process.execPath, [script, "--root", directory, ...args], { encoding: "utf8", timeout: 30_000 });

    const stale = run("--check");
    expect(stale.status).toBe(1);
    expect(stale.stderr).toContain("index.ts");

    expect(run().status).toBe(0);
    expect(run("--check").status).toBe(0);
    expect(run("--bogus").status).toBe(2);
  });
});

describe("paths that need the mirror generate it", () => {
  const ensure = "home/apps/_shared/ensure-office-engine.mjs";
  const sync = "scripts/sync-office-engine.mjs";
  const runNode = (cwd: string, ...args: string[]) =>
    spawnSync(process.execPath, args, { cwd, encoding: "utf8", timeout: 60_000 });

  it("an office app build regenerates a missing or stale mirror inside a checkout", () => {
    const directory = makeCheckout([sync, ensure]);
    const app = join(directory, "home/apps/docs");
    mkdirSync(app, { recursive: true });

    const first = runNode(app, "../_shared/ensure-office-engine.mjs");
    expect(first.status, first.stderr).toBe(0);
    expect(existsSync(join(directory, MIRROR, "index.ts"))).toBe(true);

    write(directory, `${MIRROR}/index.ts`, "stale\n");
    write(directory, `${MIRROR}/removed.ts`, "stale\n");
    expect(runNode(app, "../_shared/ensure-office-engine.mjs").status).toBe(0);
    expect(readFileSync(join(directory, MIRROR, "index.ts"))).toEqual(readFileSync(join(directory, SOURCE, "index.ts")));
    expect(existsSync(join(directory, MIRROR, "removed.ts"))).toBe(false);
  });

  it("an office app build on an owner's computer uses the shipped copy and fails clearly without one", () => {
    // $MATRIX_HOME/apps/<slug>: no repository, no packages/office, no sync script.
    const home = makeRoot({});
    mkdirSync(join(home, "apps/docs"), { recursive: true });
    cpSync(join(root, ensure), join(home, "apps/_shared/ensure-office-engine.mjs"));

    const missing = runNode(join(home, "apps/docs"), "../_shared/ensure-office-engine.mjs");
    expect(missing.status).toBe(1);
    expect(missing.stderr).toContain("office-engine is missing");

    write(home, "apps/_shared/office-engine/index.ts", "shipped\n");
    const shipped = runNode(join(home, "apps/docs"), "../_shared/ensure-office-engine.mjs");
    expect(shipped.status, shipped.stderr).toBe(0);
    expect(readFileSync(join(home, "apps/_shared/office-engine/index.ts"), "utf8")).toBe("shipped\n");
  });

  it("build-default-apps generates the mirror before building, and keeps the shipped copy without the sync script", () => {
    const checkout = makeCheckout(["scripts/build-default-apps.mjs", sync]);
    mkdirSync(join(checkout, "home/apps"), { recursive: true });
    const built = runNode(checkout, "scripts/build-default-apps.mjs", "home/apps");
    expect(built.status, built.stderr).toBe(0);
    expect(listFiles(join(checkout, MIRROR))).toEqual(["README.md", ...listFiles(join(checkout, SOURCE))].sort());

    // Docker runtime image and host bundle: build-default-apps ships without the sync script.
    const runtime = makeCheckout(["scripts/build-default-apps.mjs"]);
    write(runtime, `${MIRROR}/index.ts`, "shipped\n");
    const rebuilt = runNode(runtime, "scripts/build-default-apps.mjs", "home/apps");
    expect(rebuilt.status, rebuilt.stderr).toBe(0);
    expect(listFiles(join(runtime, MIRROR))).toEqual(["index.ts"]);
  });

  it("the host bundle generates the mirror before the template manifest and ships it with home", () => {
    const script = readFileSync(join(root, "scripts/build-host-bundle.sh"), "utf8");
    const buildApps = script.indexOf('node "$ROOT_DIR/scripts/build-default-apps.mjs" "$ROOT_DIR/home/apps"');
    expect(buildApps).toBeGreaterThanOrEqual(0);
    expect(buildApps).toBeLessThan(script.indexOf("generateTemplateManifest"));
    expect(buildApps).toBeLessThan(script.indexOf("scripts/copy-host-runtime-home.sh"));

    // The home copy and the template manifest read the filesystem, not git, so the ignored copy ships.
    const source = makeRoot({
      ".gitignore": "apps/_shared/office-engine/\n",
      "apps/_shared/office-engine/index.ts": "engine\n",
      "apps/docs/node_modules/x.js": "dependency\n",
    });
    const destination = join(makeRoot({}), "home");
    const copied = spawnSync("bash", [join(root, "scripts/copy-host-runtime-home.sh"), source, destination], {
      encoding: "utf8",
      timeout: 30_000,
    });
    expect(copied.status, copied.stderr).toBe(0);
    expect(readFileSync(join(destination, "apps/_shared/office-engine/index.ts"), "utf8")).toBe("engine\n");
    expect(generateTemplateManifest(destination)).toHaveProperty(["apps/_shared/office-engine/index.ts"]);
  });
});

describe("mirrored office engine", () => {
  it("exports the same error codes as the package source", () => {
    expect(mirroredErrors.OFFICE_ERROR_CODES).toEqual(OFFICE_ERROR_CODES);
  });

  it("recognises an OfficeError from the other copy of the class by shape", () => {
    const cause = new Error("inflate failed");
    const fromMirror = new mirroredErrors.OfficeError("zip_limit_exceeded", "entry too large", {
      cause,
      details: { entry: "word/document.xml", limit: 10 },
    });

    expect(fromMirror).toBeInstanceOf(Error);
    expect(fromMirror).not.toBeInstanceOf(OfficeError);
    expect(isOfficeError(fromMirror)).toBe(true);
    expect(isOfficeError(fromMirror, "zip_limit_exceeded")).toBe(true);
    expect(isOfficeError(fromMirror, "not_a_zip", "corrupt_package")).toBe(false);
    expect(fromMirror.cause).toBe(cause);
    expect(fromMirror.details).toEqual({ entry: "word/document.xml", limit: 10 });
    expect(Object.isFrozen(fromMirror.details)).toBe(true);
  });

  it("keeps messages and details out of the client-safe JSON form", () => {
    const error = new OfficeError("stale_reference", "block b12 no longer contains \"secret clause\"");
    expect(JSON.parse(JSON.stringify(error))).toEqual({ name: "OfficeError", code: "stale_reference" });
    expect(error.details).toEqual({});
  });

  it("does not mistake other errors for an OfficeError", () => {
    const impostor = Object.assign(new Error("x"), { name: "OfficeError", code: "made_up" });
    expect(isOfficeError(impostor)).toBe(false);
    expect(isOfficeError(Object.assign(new Error("x"), { code: "not_a_zip" }))).toBe(false);
    expect(isOfficeError({ name: "OfficeError", code: "not_a_zip" })).toBe(false);
    expect(isOfficeError(null)).toBe(false);
  });
});
