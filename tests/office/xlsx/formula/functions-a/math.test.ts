describe("array arguments of scalar math functions", () => {
  const { run } = setup();
  it("applies ROUND element by element", () => {
    expect(run("ROUND({1.25,2.35},1)")).toMatchObject({ kind: "array", values: [[1.3, 2.4]] });
  });
  it("applies ABS to a range", () => {
    expect(run("ABS(-A1:A3)")).toMatchObject({ kind: "array", values: [[10], [20], [30]] });
  });
});
