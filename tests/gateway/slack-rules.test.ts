import { afterEach, expect, it } from "vitest";
import { createRealBotStateDatabase, insertChat } from "./bots/bot-state-support.js";
import { createSlackRulesRepository } from "../../packages/gateway/src/slack/rules.js";
const clean: Array<() => Promise<void>> = [];
afterEach(async () => { for (const close of clean.splice(0).reverse())
    await close(); });
it("persists one owner/bot/enrollment standing policy across repository recreation", async () => {
    const f = await createRealBotStateDatabase();
    clean.push(f.destroy);
    const target = { ownerId: "user_rules", botId: "bot_0123456789abcdef", chatId: "chat_rules", runtimeId: "preview_runtime" };
    await insertChat(f.db, target.chatId, target.ownerId);
    await f.db.insertInto("bot_chat_bindings").values({ owner_id: target.ownerId, bot_id: target.botId, chat_id: target.chatId, kind: "direct", created_at: new Date(), removed_at: null }).execute();
    const input = { ...target, grantId: "a".repeat(64), sourceId: "slack_enrolled_" + "b".repeat(32), channelId: "C123", label: "#tech", originMessageId: "msg_owner", now: "2026-11-20T08:00:00Z", definition: { trigger: "new_message" as const, cadence: { kind: "coalesce" as const, seconds: 60 }, focus: "release risks", language: "English" } };
    const rule = await createSlackRulesRepository(f.db).save(input);
    expect(rule).toMatchObject({ status: "active", revision: 1, definition: input.definition });
    expect(await createSlackRulesRepository(f.db).list(target)).toEqual([rule]);
    const again = await createSlackRulesRepository(f.db).save(input);
    expect(again.ruleId).toBe(rule.ruleId);
});
it("ordinary signed source follows the durable coalescing policy instead of the legacy mention policy", async () => {
    const { createHash } = await import("node:crypto");
    const { createPrivateSlackThreadContext } = await import("../../packages/gateway/src/slack/private-thread-context.js");
    const { createSlackMentionSummaries } = await import("../../packages/gateway/src/slack/mention-summary.js");
    const f = await createRealBotStateDatabase();
    clean.push(f.destroy);
    const target = { ownerId: "user_rules", botId: "bot_0123456789abcdef", chatId: "chat_rules", runtimeId: "preview_runtime" };
    await insertChat(f.db, target.chatId, target.ownerId);
    await f.db.insertInto("bot_chat_bindings").values({ owner_id: target.ownerId, bot_id: target.botId, chat_id: target.chatId, kind: "direct", created_at: new Date(), removed_at: null }).execute();
    let now = new Date("2026-11-20T08:00:00Z");
    const rules = createSlackRulesRepository(f.db);
    const rule = await rules.save({ ...target, grantId: "a".repeat(64), sourceId: "slack_enrolled_" + "b".repeat(32), channelId: "C123", label: "#tech", originMessageId: "msg_owner", now: now.toISOString(), definition: { trigger: "new_message", cadence: { kind: "coalesce", seconds: 60 }, focus: "release risks", language: "English" } });
    let service = await createSlackMentionSummaries({ db: f.db, ...target, now: () => now, authorize: async () => true, readThread: async () => ({ recipientUserId: "U123", messages: [], partial: false }) });
    clean.push(service.close);
    let context = await createPrivateSlackThreadContext({ db: f.db, ...target, authorize: async () => true, onReceive: service.receive });
    const text = "ordinary update without a mention";
    const env = { ...target, grantId: rule.grantId, event: { appId: "A123", teamId: "T123", channelId: "C123", threadTs: "1795161601.000001", ts: "1795161601.000001", eventId: "EvRule", userId: "U456", text }, source: { version: 1 as const, ownerMention: false, textDigest: createHash("sha256").update(text).digest("hex"), proof: "b".repeat(64) } };
    await context.receive(env);
    await context.receive({ ...env, event: { ...env.event, eventId: "EvRule2", ts: "1795161602.000001" } });
    const submitted: unknown[] = [];
    service.attach(async (record) => { submitted.push(record); return { runId: "run_rule_summary" }; });
    await service.drain();
    expect(submitted).toHaveLength(0);
    await service.close();
    service=await createSlackMentionSummaries({db:f.db,...target,now:()=>now,authorize:async()=>true,readThread:async()=>({recipientUserId:"U123",messages:[],partial:false})});
    clean.push(service.close);
    context=await createPrivateSlackThreadContext({db:f.db,...target,authorize:async()=>true,onReceive:service.receive});
    service.attach(async record=>{submitted.push(record);return {runId:"run_rule_summary"};});
    now = new Date(now.getTime() + 61000);
    await service.drain();
    expect(submitted).toHaveLength(1);
    expect(JSON.stringify(submitted)).not.toContain(text);
    expect(await f.db.selectFrom("chat_runs").select("id").execute()).toHaveLength(0);
    await rules.change(target, { ruleId: rule.ruleId, baseRevision: 1, operation: "pause", originMessageId: "msg_pause", now: now.toISOString() });
    await context.receive({ ...env, summary: { ruleId: "legacy", version: 1, proof: "c".repeat(64) }, event: { ...env.event, eventId: "EvAfterPause", ts: "1795161700.000001" } });
    now = new Date(now.getTime() + 61000);
    await service.drain();
    expect(submitted).toHaveLength(1);
});
