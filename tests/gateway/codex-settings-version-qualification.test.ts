/** Only the fixed fixture graph is traversed; every reference must resolve. */
function authenticationContract(schema: Schema) {
  const definitions: Record<string, Schema> = {};
  const visit = (value: unknown): void => {
    if (!value || typeof value !== 'object') return;
    if (Array.isArray(value)) { value.forEach(visit); return; }
    const entry = object(value);
    if (typeof entry.$ref === 'string' && !Object.hasOwn(definitions, entry.$ref)) {
      definitions[entry.$ref] = resolve(schema, entry.$ref);
      visit(definitions[entry.$ref]);
    }
    Object.values(entry).forEach(visit);
  };
  for (const ref of roots) { definitions[ref] = resolve(schema, ref); visit(definitions[ref]); }
  return definitions;
}
function variant(schema: Schema, ref: string, field: string, literal: string) {
  const branches = resolve(schema, ref).oneOf;
  if (!Array.isArray(branches)) throw new Error('Expected schema alternatives');
  const matches = branches.map(object).filter(branch => {
    const values = object(object(branch.properties)[field]).enum;
    return Array.isArray(values) && values.includes(literal);
  });
  expect(matches).toHaveLength(1);
  return matches[0]!;
}
