    expect(Object.keys(object(params.properties))).toEqual(['type']);
    expect(JSON.stringify(params)).not.toMatch(/experimental|unstable|internal/i);
    expect(variant(schema, '#/definitions/v2/LoginAccountResponse', 'type', 'chatgptDeviceCode')).toMatchObject({
      required: ['loginId', 'type', 'userCode', 'verificationUrl'],
    });
    expect(variant(schema, '#/definitions/ServerNotification', 'method', 'account/login/completed'))
