type Schema = Record<string, unknown>;
function object(value: unknown): Schema {
  if (!value || typeof value !== 'object' || Array.isArray(value)) throw new Error('Expected schema object');
  return value as Schema;
}
function resolve(schema: Schema, ref: string): Schema {
  if (!ref.startsWith('#/definitions/')) throw new Error('Expected local definition reference');
  return ref.slice(2).split('/').reduce((value, key) => object(value[key.replaceAll('~1', '/').replaceAll('~0', '~')]), schema);
}
