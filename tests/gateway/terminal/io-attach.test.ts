import { EventEmitter } from "node:events";
import { randomUUID } from "node:crypto";
import { PassThrough } from "node:stream";
import { createServer, type Socket } from "node:net";
import { mkdir, mkdtemp, rm } from "node:fs/promises";
import { join } from "node:path";
import { afterEach, expect, it, vi } from "vitest";
import { attachTerminalIo } from "../../../packages/gateway/src/terminal/io-attach.js";
const cleanup: (() => Promise<unknown>)[] = [];
afterEach(async () => { for (const close of cleanup.splice(0).reverse()) await close(); });
it("sends actual pane size, resizes, forwards raw I/O and detaches without any stop or authority frame", async () => {
  const root = await mkdtemp("/tmp/t7io-"); cleanup.push(() => rm(root, { recursive: true, force: true }));
  const dir = join(root, "matrix-terminal-" + randomUUID().replaceAll("-", "")); await mkdir(dir, { mode: 0o700 });
  const path = join(dir, "io.sock"), frames: unknown[] = []; let peer: Socket | undefined;
  const server = createServer(socket => { peer = socket; socket.setEncoding("utf8"); let bytes = "";
    socket.on("data", data => { bytes += data; let at; while ((at = bytes.indexOf("\n")) >= 0) { frames.push(JSON.parse(bytes.slice(0, at))); bytes = bytes.slice(at + 1); } }); });
  await new Promise<void>(resolve => server.listen(path, resolve)); cleanup.push(() => new Promise<void>(resolve => { peer?.destroy(); server.close(() => resolve()); }));
  const input = Object.assign(new PassThrough(), { isTTY: true, isRaw: false, setRawMode: vi.fn() });
  const output = Object.assign(new PassThrough(), { columns: 107, rows: 35 }); let displayed = ""; output.on("data", bytes => displayed += bytes.toString());
  const resizeEvents = new EventEmitter(), signal = new AbortController();
  const attachment = await attachTerminalIo({ path, input, output, resizeEvents, signal: signal.signal });
  cleanup.push(async () => { attachment.close(); await attachment.closed; });
  await vi.waitFor(() => expect(frames[0]).toEqual({ type: "resize", cols: 107, rows: 35 }));
  input.write("printf hello\n"); output.columns = 113; output.rows = 41; resizeEvents.emit("SIGWINCH");
  peer!.write("native output\r\n");
  await vi.waitFor(() => { expect(displayed).toBe("native output\r\n"); expect(frames).toContainEqual({ type: "input", data: "printf hello\n" }); expect(frames).toContainEqual({ type: "resize", cols: 113, rows: 41 }); });
  signal.abort(); await attachment.closed;
  expect(input.setRawMode.mock.calls).toEqual([[true], [false]]); expect(resizeEvents.listenerCount("SIGWINCH")).toBe(0);
  expect(frames.every(frame => ["resize", "input", "ping"].includes((frame as { type: string }).type))).toBe(true);
});
