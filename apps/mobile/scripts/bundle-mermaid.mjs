// Commit the offline browser distribution, as with bundle-xterm.mjs.
// Regenerate after changing the pinned mermaid dev dependency.
import { createRequire } from "node:module";
import { dirname, resolve } from "node:path";
import { readFile, writeFile } from "node:fs/promises";
const require = createRequire(import.meta.url);
const packagePath = require.resolve("mermaid/package.json");
const { version } = JSON.parse(await readFile(packagePath, "utf8"));
const distribution = await readFile(resolve(dirname(packagePath), "dist/mermaid.min.js"), "utf8");
const output = `// @generated by scripts/bundle-mermaid.mjs. Mermaid ${version}, MIT.\n// Offline distribution; do not edit by hand.\nexport const MERMAID_VERSION = ${JSON.stringify(version)};\nexport const MERMAID_JS = ${JSON.stringify(distribution)};\n`;
await writeFile(new URL("../components/chat/mermaid-bundle.ts", import.meta.url), output);
console.log(`Bundled Mermaid ${version} for offline diagrams (${Math.round(distribution.length / 1024)} KiB).`);
