// Canonical contracts are copied at repository build time. Owner copies retain
// this generated snapshot so source rebuilds do not require the monorepo.
import {readFile,writeFile} from 'node:fs/promises';
const canonical=new URL('../../../packages/contracts/src/app-gallery.ts',import.meta.url);
const snapshot=new URL('./src/generated-contract.ts',import.meta.url);
try {
 const source=await readFile(canonical,'utf8');
 await writeFile(snapshot,'// Generated by sync-contract.mjs from packages/contracts/src/app-gallery.ts. Do not edit.\n'+source);
} catch(error) {
 if(error?.code!=='ENOENT')throw error;
 const existing=await readFile(snapshot,'utf8');
 if(!existing.startsWith('// Generated by sync-contract.mjs'))throw new Error('Gallery contract snapshot unavailable');
}
