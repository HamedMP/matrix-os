// CI source classification for ci.yml's `changes` job, extracted for focused contracts.
import {spawnSync} from 'node:child_process';
import {pathToFileURL} from 'node:url';
export const sourceChangeScript=[
  "set -euo pipefail",
  "",
  "# Main runs everything except docs-only pushes, diffed against the commit before the push.",
  "if [ \"$GITHUB_EVENT_NAME\" = \"push\" ] && [ \"$GITHUB_REF\" = \"refs/heads/main\" ]; then",
  "  echo \"trigger_requested=true\" >> \"$GITHUB_OUTPUT\"",
  "  echo \"os_view_parity_tests=true\" >> \"$GITHUB_OUTPUT\"",
  "  echo \"unit_scope=full\" >> \"$GITHUB_OUTPUT\"",
  "  echo \"e2e_tests=true\" >> \"$GITHUB_OUTPUT\"",
  "  if [[ \"${MAIN_BEFORE:-}\" =~ ^[0-9a-f]{40}$ ]] && [[ ! \"$MAIN_BEFORE\" =~ ^0+$ ]] && git fetch --no-tags --depth=1 origin \"$MAIN_BEFORE\"; then",
  "    echo \"base_sha=$MAIN_BEFORE\" >> \"$GITHUB_OUTPUT\"",
  "    echo \"bootstrap=false\" >> \"$GITHUB_OUTPUT\"",
  "    main_files=\"$(git diff --name-only \"$MAIN_BEFORE\" \"$GITHUB_SHA\")\"",
  "    main_should_run=false",
  "    main_docs=false",
  "    while IFS= read -r file; do",
  "      [ -z \"$file\" ] && continue",
  "      case \"$file\" in",
  "        docs/*|specs/*|*.md) main_docs=true ;;",
  "        *) main_should_run=true ;;",
  "      esac",
  "    done <<EOF",
  "$main_files",
  "EOF",
  "  else",
  "    # First push or unreachable base: run everything and let diff-based checks scan the whole tree.",
  "    echo \"bootstrap=true\" >> \"$GITHUB_OUTPUT\"",
  "    main_should_run=true",
  "    main_docs=true",
  "  fi",
  "  echo \"should_run=$main_should_run\" >> \"$GITHUB_OUTPUT\"",
  "  echo \"docs_contract_tests=$main_docs\" >> \"$GITHUB_OUTPUT\"",
  "  echo \"CI relevant changes: $main_should_run\"",
  "  exit 0",
  "fi",
  "",
  "# Manual and merge-queue runs must execute CI regardless of changed paths.",
  "if [ \"$GITHUB_EVENT_NAME\" = \"workflow_dispatch\" ] || [ \"$GITHUB_EVENT_NAME\" = \"merge_group\" ]; then",
  "  echo \"trigger_requested=true\" >> \"$GITHUB_OUTPUT\"",
  "  echo \"should_run=true\" >> \"$GITHUB_OUTPUT\"",
  "  echo \"docs_contract_tests=false\" >> \"$GITHUB_OUTPUT\"",
  "  echo \"os_view_parity_tests=true\" >> \"$GITHUB_OUTPUT\"",
  "  echo \"unit_scope=full\" >> \"$GITHUB_OUTPUT\"",
  "  echo \"e2e_tests=true\" >> \"$GITHUB_OUTPUT\"",
  "  echo \"CI relevant changes: true ($GITHUB_EVENT_NAME always runs)\"",
  "  exit 0",
  "fi",
  "",
  "should_run_trigger=true",
  "if [ \"$GITHUB_EVENT_NAME\" = \"pull_request\" ]; then",
  "  should_run_trigger=false",
  "  # Drafts never run CI; every non-draft head does, with no label required.",
  "  if [ \"${PR_DRAFT:-true}\" = \"false\" ] && { [ \"$PR_ACTION\" = \"opened\" ] || [ \"$PR_ACTION\" = \"ready_for_review\" ] || [ \"$PR_ACTION\" = \"synchronize\" ] || [ \"$PR_ACTION\" = \"reopened\" ]; }; then",
  "    should_run_trigger=true",
  "  fi",
  "fi",
  "",
  "if [ \"$should_run_trigger\" != \"true\" ]; then",
  "  echo \"trigger_requested=false\" >> \"$GITHUB_OUTPUT\"",
  "  echo \"should_run=false\" >> \"$GITHUB_OUTPUT\"",
  "  echo \"docs_contract_tests=false\" >> \"$GITHUB_OUTPUT\"",
  "  echo \"os_view_parity_tests=false\" >> \"$GITHUB_OUTPUT\"",
  "  echo \"unit_scope=full\" >> \"$GITHUB_OUTPUT\"",
  "  echo \"e2e_tests=false\" >> \"$GITHUB_OUTPUT\"",
  "  echo \"CI trigger not requested: drafts do not run CI. Mark the PR ready for review, push, or run manually.\"",
  "  exit 0",
  "fi",
  "",
  "echo \"trigger_requested=true\" >> \"$GITHUB_OUTPUT\"",
  "git fetch --no-tags --depth=1 origin \"$GITHUB_BASE_REF\"",
  "changed_files=\"$(git diff --name-only \"origin/$GITHUB_BASE_REF\" \"$GITHUB_SHA\")\"",
  "os_view_parity_tests=\"$(printf '%s\\n' \"$changed_files\" | node scripts/ci/os-view-parity-plan.mjs)\"",
  "# Ordinary PRs run only the unit tests their change reaches and skip unrelated E2E; main stays full.",
  "printf '%s\\n' \"$changed_files\" | node scripts/ci/pr-test-plan.mjs >> \"$GITHUB_OUTPUT\"",
  "",
  "should_run=false",
  "docs_contract_tests=false",
  "while IFS= read -r file; do",
  "  [ -z \"$file\" ] && continue",
  "  case \"$file\" in",
  "    docs/*|specs/*|*.md) docs_contract_tests=true ;;",
  "    *) should_run=true ;;",
  "  esac",
  "done <<EOF",
  "$changed_files",
  "EOF",
  "",
  "echo \"should_run=$should_run\" >> \"$GITHUB_OUTPUT\"",
  "echo \"docs_contract_tests=$docs_contract_tests\" >> \"$GITHUB_OUTPUT\"",
  "echo \"os_view_parity_tests=$os_view_parity_tests\" >> \"$GITHUB_OUTPUT\"",
  "echo \"CI relevant changes: $should_run\"",
  "echo \"Docs contract tests: $docs_contract_tests\"",
  "echo \"OS-view parity tests: $os_view_parity_tests\"",
  "printf '%s\\n' \"$changed_files\" | node scripts/ci/pr-test-plan.mjs",
  "",
].join('\n');
if(process.argv[1]&&import.meta.url===pathToFileURL(process.argv[1]).href){
 const result=spawnSync('bash',['-c',sourceChangeScript],{stdio:'inherit',env:process.env,timeout:180000});
 if(result.error)throw result.error;process.exit(result.status??1);
}
