import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const args = process.argv.slice(2);
if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) {
  throw new Error("Usage: node scripts/generate-chat-agent-inspirations.mjs [--check]");
}
const checkOnly = args[0] === "--check";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = resolve(root, "specs/121-chat-agent-templates/xai-marketplace-inventory.json");
const outputPath = resolve(root, "packages/ui/src/chat-agents/agent-inspirations.generated.ts");
const source = JSON.parse(await readFile(sourcePath, "utf8"));
const inspirations = source.bots.map((bot) => ({
  id: bot.id,
  name: bot.name,
  creatorName: bot.creatorName,
  categories: bot.categories,
  description: bot.description,
  skills: bot.skills.names,
  routines: bot.routines.names,
  integrations: bot.integrations.names,
  sourceUrl: bot.sourceUrl,
}));

const contents = `// Generated by scripts/generate-chat-agent-inspirations.mjs from the public research inventory.\n`
  + `// Keep this metadata-only: third-party private prompts are not copied into Matrix.\n`
  + `export type AgentInspiration = {\n`
  + `  id: string; name: string; creatorName: string; categories: string[]; description: string;\n`
  + `  skills: string[]; routines: string[]; integrations: string[]; sourceUrl: string;\n`
  + `};\n\n`
  + `export const agentInspirations: AgentInspiration[] = ${JSON.stringify(inspirations, null, 2)};\n`;

if (checkOnly) {
  let existing;
  try {
    existing = await readFile(outputPath, "utf8");
  } catch (error) {
    if (!(error instanceof Error) || !("code" in error) || error.code !== "ENOENT") throw error;
  }
  if (existing !== contents) {
    console.error("Agent inspirations are stale or missing. Run node scripts/generate-chat-agent-inspirations.mjs.");
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, contents, "utf8");
}
