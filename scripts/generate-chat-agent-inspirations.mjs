import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const args = process.argv.slice(2);
if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) {
  throw new Error("Usage: node scripts/generate-chat-agent-inspirations.mjs [--check]");
}
const checkOnly = args[0] === "--check";
const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const sourcePath = resolve(root, "specs/121-chat-agent-templates/xai-marketplace-inventory.json");
const outputPath = resolve(root, "packages/ui/src/chat-agents/agent-inspirations.generated.ts");
const mobileOutputPath = resolve(root, "apps/mobile/components/agents/agent-inspirations.generated.ts");
// The marketplace's own collection, which the web filters out wherever it shows a category.
const SOURCE_COLLECTION = "From Grok Bot Team";
const source = JSON.parse(await readFile(sourcePath, "utf8"));
const inspirations = source.bots.map((bot) => ({
  id: bot.id,
  name: bot.name,
  creatorName: bot.creatorName,
  categories: bot.categories,
  description: bot.description,
  skills: bot.skills.names,
  routines: bot.routines.names,
  integrations: bot.integrations.names,
  sourceUrl: bot.sourceUrl,
}));
// Native Mobile cannot import the web package, so it gets its own copy: only the
// fields its gallery reads, one inspiration per line.
const mobileInspirations = inspirations.map((inspiration) => ({
  id: inspiration.id,
  name: inspiration.name,
  categories: inspiration.categories.filter((category) => category !== SOURCE_COLLECTION),
  description: inspiration.description,
  skills: inspiration.skills,
  integrations: inspiration.integrations,
}));

const header = `// Generated by scripts/generate-chat-agent-inspirations.mjs from the public research inventory.\n`
  + `// Keep this metadata-only: third-party private prompts are not copied into Matrix.\n`;
const outputs = [
  {
    path: outputPath,
    contents: header
      + `export type AgentInspiration = {\n`
      + `  id: string; name: string; creatorName: string; categories: string[]; description: string;\n`
      + `  skills: string[]; routines: string[]; integrations: string[]; sourceUrl: string;\n`
      + `};\n\n`
      + `export const agentInspirations: AgentInspiration[] = ${JSON.stringify(inspirations, null, 2)};\n`,
  },
  {
    path: mobileOutputPath,
    contents: header
      + `// The web's copy is packages/ui/src/chat-agents/agent-inspirations.generated.ts.\n`
      + `export type AgentInspiration = {\n`
      + `  id: string; name: string; categories: string[]; description: string;\n`
      + `  skills: string[]; integrations: string[];\n`
      + `};\n\n`
      + `export const agentInspirations: AgentInspiration[] = [\n`
      + mobileInspirations.map((inspiration) => `  ${JSON.stringify(inspiration)},\n`).join("")
      + `];\n`,
  },
];

if (checkOnly) {
  for (const output of outputs) {
    let existing;
    try {
      existing = await readFile(output.path, "utf8");
    } catch (error) {
      if (!(error instanceof Error) || !("code" in error) || error.code !== "ENOENT") throw error;
    }
    if (existing !== output.contents) {
      console.error("Agent inspirations are stale or missing. Run node scripts/generate-chat-agent-inspirations.mjs.");
      process.exitCode = 1;
    }
  }
} else {
  for (const output of outputs) await writeFile(output.path, output.contents, "utf8");
}
