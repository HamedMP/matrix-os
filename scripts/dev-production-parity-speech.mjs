// Keep platform-owned credentials out of build arguments and guest cloud-init.
// Only settings consumed by the platform speech config cross this boundary.
const SPEECH_ENV_NAMES = [
  "PLATFORM_SPEECH_ENABLED",
  "PLATFORM_SPEECH_PROVIDER",
  "PLATFORM_SPEECH_SECRET",
  "PLATFORM_SPEECH_POLICY_REVISION",
  "PLATFORM_SPEECH_OPENAI_API_KEY",
  "PLATFORM_SPEECH_MODEL",
  "PLATFORM_SPEECH_SYNTHESIS_MODEL",
  "PLATFORM_SPEECH_SYNTHESIS_VOICE",
  "PLATFORM_SPEECH_MICROUSD_PER_MINUTE",
  "PLATFORM_SPEECH_SYNTHESIS_MICROUSD_PER_MINUTE",
  "PLATFORM_SPEECH_MONTHLY_BUDGET_MICROUSD",
  "PLATFORM_SPEECH_MONTHLY_PROMOTIONAL_CREDIT_MICROUSD",
  "PLATFORM_SPEECH_FUNDING_SOURCES",
  "PLATFORM_SPEECH_PREVIEW_NO_CHARGE",
  "PLATFORM_SPEECH_PREVIEW_MAX_OPERATIONS_PER_RUNTIME",
  "PLATFORM_SPEECH_PREVIEW_NOT_AFTER",
  "PLATFORM_SPEECH_GLOBAL_CONCURRENCY",
  "PLATFORM_SPEECH_OWNER_CONCURRENCY",
  "PLATFORM_SPEECH_OWNER_REQUESTS_PER_MINUTE",
  "PLATFORM_SPEECH_OWNER_AUDIO_ENABLED",
  "PLATFORM_SPEECH_MAX_BYTES",
  "PLATFORM_SPEECH_MAX_DURATION_MS",
  "PLATFORM_SPEECH_MAX_TRANSCRIPT_CHARS",
];

export function platformSpeechEnvironment(env) {
  return Object.fromEntries(SPEECH_ENV_NAMES
    .filter((name) => env[name] !== undefined)
    .map((name) => [name, env[name]]));
}
